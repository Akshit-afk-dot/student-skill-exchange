export interface CatalogEntry {
  name: string;
  aliases: string[];
  category: SkillCategoryName;
}

/** The catalogue as flat entries, with each `Name|alias` string split apart. */
export function catalogEntries(): CatalogEntry[] {
  return Object.entries(SKILL_CATALOG).flatMap(([category, entries]) =>
    entries.map((entry) => {
      const [name = '', ...aliases] = entry.split('|').map((part) => part.trim());
      return { name, aliases, category: category as SkillCategoryName };
    }),
  );
}
